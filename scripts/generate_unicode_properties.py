#!/usr/bin/env python3
"""Generate immutable scalar-property tables from the pinned Unicode database."""
import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'data/unicode/17.0.0'
INPUTS = {
    'CaseFolding.txt': 'ff8d8fefbf123574205085d6714c36149eb946d717a0c585c27f0f4ef58c4183',
    'DerivedGeneralCategory.txt': 'd62e5bab70ca74f099343f71224fa051cb1fdd61a1ab45c0488c44cfc0b6102e',
    'LICENSE.txt': 'e7a93b009565cfce55919a381437ac4db883e9da2126fa28b91d12732bc53d96',
}

OPERATIONS = '''
# Both tables contain sorted pairs; find the final pair whose key is <= code.
local function the Unicode property index for {integer:code} in {a pointer to integer:data} containing {integer:count} pairs:
    execute:
        set low to 0
        set high to count
        loop while low < high:
            set middle to low + ((high - low) / 2)
            if (the item at (middle * 2) in data) <= code:
                set low to middle + 1
            else:
                set high to middle
        return low - 1

to get [the Unicode simple case fold of] {integer:code}:
    require condition (0 <= code <= 1114111) reporting "A Unicode code point is required"
    set data to Unicode simple fold data
    set index to the Unicode property index for code in data containing (Unicode simple fold count) pairs
    if index >= 0:
        if (the item at (index * 2) in data) = code:
            return the item at ((index * 2) + 1) in data
    return code

# Identifier word characters: letters, marks, numbers, connectors and join controls.
to get {integer:code} [is a Unicode word character]:
    require condition (0 <= code <= 1114111) reporting "A Unicode code point is required"
    set data to Unicode word range data
    set index to the Unicode property index for code in data containing (Unicode word range count) pairs
    if index >= 0:
        return code <= (the item at ((index * 2) + 1) in data)
    return false
'''


def records(name):
    contents = (SOURCE / name).read_bytes()
    if hashlib.sha256(contents).hexdigest() != INPUTS[name]:
        raise ValueError(f'The pinned Unicode input changed: {name}')
    for line in contents.decode().splitlines():
        line = line.split('#', 1)[0].strip()
        if line:
            yield [field.strip() for field in line.split(';')]


def tables():
    folds = {}
    for source, status, mapping, *_ in records('CaseFolding.txt'):
        if status in {'C', 'S'}:
            values = mapping.split()
            if len(values) != 1:
                raise ValueError('A simple case fold must have one target')
            folds[int(source, 16)] = int(values[0], 16)
    ranges = [(0x200C, 0x200D)]  # Join controls are part of identifier words.
    for source, category in records('DerivedGeneralCategory.txt'):
        if category[0] in 'LMN' or category == 'Pc':
            bounds = [int(value, 16) for value in source.split('..')]
            ranges.append((bounds[0], bounds[-1]))
    merged = []
    for start, end in sorted(ranges):
        if merged and start <= merged[-1][1] + 1:
            merged[-1] = (merged[-1][0], max(end, merged[-1][1]))
        else:
            merged.append((start, end))
    return sorted(folds.items()), merged


def array(name, values):
    lines = [f'local function {name}:', '    replacement:',
             '        (a static reference to [']
    for start in range(0, len(values), 12):
        line = ', '.join(map(str, values[start:start + 12]))
        lines.append('            ' + line + (',' if start + 12 < len(values) else ''))
    lines.append('        ]) as a pointer to integer')
    return '\n'.join(lines)


def generate():
    folds, words = tables()
    license_bytes = (SOURCE / 'LICENSE.txt').read_bytes()
    if hashlib.sha256(license_bytes).hexdigest() != INPUTS['LICENSE.txt']:
        raise ValueError('The pinned Unicode license changed')
    notice = '\n'.join('# ' + line for line in license_bytes.decode().splitlines())
    return (f'# Generated by scripts/generate_unicode_properties.py; Unicode 17.0.0.\n'
            f'# Sources: data/unicode/17.0.0; do not edit these tables.\n{notice}\n\n'
            f'import lib/sections.dl\n\n'
            f'local function [Unicode simple fold count]:\n    replacement:\n        {len(folds)}\n\n'
            f'local function [Unicode word range count]:\n    replacement:\n        {len(words)}\n\n'
            + array('Unicode simple fold data', [value for pair in folds for value in pair])
            + '\n\n'
            + array('Unicode word range data', [value for pair in words for value in pair])
            + '\n' + OPERATIONS)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'lib/unicode_properties.dl'
    output = generate()
    if args.check:
        if target.read_text() != output:
            raise SystemExit('Regenerate lib/unicode_properties.dl')
    else:
        target.write_text(output)
    folds, words = tables()
    print(f'Unicode 17.0.0: {len(folds)} simple folds, {len(words)} word ranges')


if __name__ == '__main__':
    main()
